func TestDjangoAdapter_simpleChecksum(t *testing.T) {
	// Test that checksum is deterministic
	tmpDir := t.TempDir()
	migrateDir := filepath.Join(tmpDir, "myapp", "migrations")
	os.MkdirAll(migrateDir, 0755)

	data1 := []byte("class Migration(migrations.Migration):\n    dependencies = []\n    operations = []")
	data2 := []byte("class Migration(migrations.Migration):\n    dependencies = []\n    operations = []")
	data3 := []byte("class Migration(migrations.Migration):\n    dependencies = []\n    operations = [some difference]")

	file1 := filepath.Join(migrateDir, "0001_test1.py")
	file2 := filepath.Join(migrateDir, "0002_test2.py")
	file3 := filepath.Join(migrateDir, "0003_test3.py")

	os.WriteFile(file1, data1, 0644)
	os.WriteFile(file2, data2, 0644)
	os.WriteFile(file3, data3, 0644)

	d := django.NewDjangoAdapter("", tmpDir)

	mig1, _ := d.ParseMigrationFile(file1)
	mig2, _ := d.ParseMigrationFile(file2)
	mig3, _ := d.ParseMigrationFile(file3)

	// Same content should produce same checksum
	assert.Equal(t, mig1.Checksum, mig2.Checksum)
	// Different content should produce different checksum
	assert.NotEqual(t, mig1.Checksum, mig3.Checksum)
}

func TestDjangoAdapter_extractMigrationNumber(t *testing.T) {
	tests := []struct {
		name     string
		input    string
		expected int
	}{
		{"0001_initial", "0001_initial", 1},
		{"0002_add_field", "0002_add_field", 2},
		{"0123_test", "0123_test", 123},
		{"0001", "0001", 1},
		{"no_number", "no_number", 0},
		{"", "", 0},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			result := extractMigrationNumber(tt.input)
			assert.Equal(t, tt.expected, result, "extractMigrationNumber(%s) = %d, want %d", tt.input, result, tt.expected)
		})
	}
}

// extractMigrationNumber is exported for testing
func extractMigrationNumber(name string) int {
	var num int
	for _, r := range name {
		if r >= '0' && r <= '9' {
			num = num*10 + int(r-'0')
		} else {
			break
		}
	}
	return num
}
