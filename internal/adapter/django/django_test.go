func TestDjangoAdapter_IsMigrationFile(t *testing.T) {
	d := django.NewDjangoAdapter("", "")

	// Valid Django migrations (NNNN_name.py in migrations/ directory)
	assert.True(t, d.IsMigrationFile("/path/to/auth/migrations/0001_initial.py"))
	assert.True(t, d.IsMigrationFile("/path/to/users/migrations/0002_add_email.py"))
	assert.True(t, d.IsMigrationFile("migrations/0003_auto_20250101.py"))

	// Invalid files
	assert.False(t, d.IsMigrationFile("README.md"))
	assert.False(t, d.IsMigrationFile("0001_initial.py")) // Not in migrations/ dir
	assert.False(t, d.IsMigrationFile("/path/to/migrations/123_initial.py")) // Not 4 digits
	assert.False(t, d.IsMigrationFile("/path/to/auth/0001_initial.txt")) // Wrong extension
	assert.False(t, d.IsMigrationFile("/path/to/auth/notmigrations/0001_initial.py")) // Wrong parent dir name
}

func TestDjangoAdapter_ParseMigrationFile(t *testing.T) {
	tmpDir := t.TempDir()
	// migrationDir should be the parent of the app directory
	migrateDir := tmpDir
	appMigrationsDir := filepath.Join(tmpDir, "myapp", "migrations")
	os.MkdirAll(appMigrationsDir, 0755)

	migrationFile := filepath.Join(appMigrationsDir, "0001_initial.py")
	content := `# Generated by Django 5.0 on 2025-01-01

from django.db import migrations, models

class Migration(migrations.Migration):

    initial = True

    dependencies = [
    ]

    operations = [
        migrations.CreateModel(
            name='User',
            fields=[
                ('id', models.BigAutoField(primary_key=True)),
                ('email', models.EmailField(max_length=254)),
            ],
        ),
    ]
`
	err := os.WriteFile(migrationFile, []byte(content), 0644)
	require.NoError(t, err)

	d := django.NewDjangoAdapter("", migrateDir)
	migration, err := d.ParseMigrationFile(migrationFile)
	require.NoError(t, err)

	assert.Equal(t, "myapp:0001_initial", migration.Version)
	assert.Equal(t, "myapp.initial", migration.Name)
	assert.Equal(t, migrationFile, migration.FilePath)
	assert.Equal(t, content, migration.UpSQL)
	assert.NotEmpty(t, migration.Checksum)
	assert.False(t, migration.Timestamp.IsZero())
}

