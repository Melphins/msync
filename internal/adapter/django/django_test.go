func TestDjangoAdapter_LoadMigrations(t *testing.T) {
	tmpDir := t.TempDir()

	// Create multiple apps with migrations
	apps := []string{"auth", "users", "contenttypes"}
	for _, app := range apps {
		migrateDir := filepath.Join(tmpDir, app, "migrations")
		os.MkdirAll(migrateDir, 0755)

		migrations := []struct {
			filename string
			content  string
		}{
			{
				fmt.Sprintf("0001_initial_%s.py", app),
				fmt.Sprintf("class Migration(migrations.Migration):\n    dependencies = []\n    operations = []\n# %s initial", app),
			},
			{
				fmt.Sprintf("0002_update_%s.py", app),
				fmt.Sprintf("class Migration(migrations.Migration):\n    dependencies = [('%s', '0001_initial_%s')]\n    operations = []\n# %s update", app, app, app),
			},
		}

		for _, m := range migrations {
			filePath := filepath.Join(migrateDir, m.filename)
			os.WriteFile(filePath, []byte(m.content), 0644)
		}
	}

	d := django.NewDjangoAdapter("", tmpDir)
	err := d.LoadMigrations()
	require.NoError(t, err)

	migs, err := d.GetMigrations()
	require.NoError(t, err)

	// Should load 6 migrations (3 apps * 2 migrations each)
	assert.Len(t, migs, 6)

	// Create a map of versions for easy lookup
	versionMap := make(map[string]string)
	for _, m := range migs {
		versionMap[m.Version] = m.Name
	}

	// Check that all expected versions exist
	expectedVersions := []string{
		"auth:0001_initial_auth",
		"auth:0002_update_auth",
		"users:0001_initial_users",
		"users:0002_update_users",
		"contenttypes:0001_initial_contenttypes",
		"contenttypes:0002_update_contenttypes",
	}
	for _, ver := range expectedVersions {
		_, exists := versionMap[ver]
		assert.True(t, exists, "expected version %s to exist", ver)
	}
}

