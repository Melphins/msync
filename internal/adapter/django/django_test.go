func TestDjangoAdapter_FindMigrationByVersion(t *testing.T) {
	tmpDir := t.TempDir()
	migrateDir := filepath.Join(tmpDir, "myapp", "migrations")
	os.MkdirAll(migrateDir, 0755)

	// Create test migrations
	for i := 1; i <= 3; i++ {
		filename := fmt.Sprintf("%04d_test_%d.py", i, i)
		filePath := filepath.Join(migrateDir, filename)
		content := fmt.Sprintf("class Migration(migrations.Migration):\n    dependencies = []\n    operations = []\n# Test %d", i)
		os.WriteFile(filePath, []byte(content), 0644)
	}

	d := django.NewDjangoAdapter("", tmpDir)
	err := d.LoadMigrations()
	require.NoError(t, err)

	// Test finding existing migration
	mig, err := d.FindMigrationByVersion("myapp:0001_test_1")
	require.NoError(t, err)
	assert.Equal(t, "myapp:0001_test_1", mig.Version)

	// Test finding another existing migration
	mig, err = d.FindMigrationByVersion("myapp:0003_test_3")
	require.NoError(t, err)
	assert.Equal(t, "myapp:0003_test_3", mig.Version)

	// Test finding non-existent migration
	_, err = d.FindMigrationByVersion("nonexistent:0001_test")
	assert.Error(t, err)
	assert.Equal(t, adapter.ErrMigrationNotFound, err)
}

